#!/usr/bin/env python3
"""Assemble the deployable site into _site/.

The Pages workflow used to do this inline in a shell block, which meant the
layout of the published site was knowledge that existed only in CI — you could
not reproduce it locally, and `make serve` served the repo root instead, where
the app lives at /plant-tree.html and the taxon pages don't exist at all. That
gap is exactly the kind of seam Sprint T was about: the thing you test is not
the thing you ship.

So assembly lives here, in one place both `make serve` and the workflow call.

    _site/
      index.html          the app (it IS the root)
      plant-tree.html     same bytes, back-compat for old links
      family/<slug>/      479 taxon pages          } build/pages.py
      order/<slug>/        86 taxon pages          }
      families/ orders/    two hubs                }
      p.css favicon.svg   shared by the pages      }
      og.jpg CNAME robots.txt sitemap.xml .nojekyll

Usage:  python3 build/site.py        (expects build.py to have run first)
"""
import pathlib
import shutil
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import pages
from build import SITE

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "_site"
APP = ROOT / "plant-tree.html"

# Copied verbatim. Missing optional files are reported, not fatal: og.jpg is
# regenerated by a separate Chrome step that CI runs after the build, and a
# local `make serve` should not require it.
#
# robots.txt and sitemap.xml are NOT here — build/pages.py generates both from
# SITE and the actual page list. The hand-written pair used to be copied from the
# repo root, where they named the host themselves and listed a single URL.
STATIC = ["og.jpg", "CNAME"]


def main():
    if not APP.exists():
        raise SystemExit(f"{APP.name} not found — run build/build.py first")

    if OUT.exists():
        shutil.rmtree(OUT)          # never serve a stale page from a previous run
    OUT.mkdir(parents=True)

    app = APP.read_bytes()
    (OUT / "index.html").write_bytes(app)       # the app is the root
    (OUT / "plant-tree.html").write_bytes(app)  # back-compat; canonical points at /
    (OUT / ".nojekyll").write_bytes(b"")

    missing = []
    for name in STATIC:
        src = ROOT / name
        if src.exists():
            shutil.copy2(src, OUT / name)
        else:
            missing.append(name)

    written = pages.build(SITE, OUT)

    total = sum(p.stat().st_size for p in OUT.rglob("*") if p.is_file())
    print(f"assembled {OUT.name}/ — app + {len(written)} pages, {total / 1024 / 1024:.1f} MB")
    if missing:
        print(f"  note: {', '.join(missing)} absent (regenerated in CI)", file=sys.stderr)


if __name__ == "__main__":
    main()
